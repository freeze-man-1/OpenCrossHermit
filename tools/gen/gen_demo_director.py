#!/usr/bin/env python3
"""Writes game/demo/demo_director.gen.inc: DemoTask's director (FUN_004e3ae0)
as a coroutine, translated by tools/ghidra2cpp.py.

The function is one frame-counted loop like the layer functions, with the
task's `this` kept in local_8 and FUN_00422360(0) (end the frame) as its
only wait, so it goes through the same translation with these rewrites:
  local_8                       -> the work area (param_1)
  FUN_00422360(0)               -> co_await yieldFrame()
  input +0x1950 & 0x8000        -> Space (Action::Skip), as elsewhere in the port
  DAT_007a4a00 + 0x8e0 = 1      -> quit the game, then co_return
and the engine calls are named in CALLS below (DemoTask's methods).
Usage: gen_demo_director.py CH.exe.c out.inc
"""
import os
import re
import sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
import ghidra2cpp as g  # noqa: E402

src = open(sys.argv[1], encoding='utf-8', errors='replace').read()
fn = g.extract(src, 'FUN_004e3ae0').replace('\r', '')
fn = re.sub(r'\blocal_8\b', 'param_1', fn)
fn = fn.replace('FUN_00422360(0);', 'co_await yieldFrame();')
fn = fn.replace('(*(uint *)(DAT_007a49fc + 0x1950) & 0x8000) != 0', 'skipPressed()')
fn = re.sub(r'\*\(undefined4 \*\)\(DAT_007a4a00 \+ 0x8e0\) = 1;\n(\s+)param_1 = 0x[0-9a-f]+;\n\s+__chkesp\(\);\n\s+return;',
            r'quitGame();\n\1co_return;', fn)
g.CALLS.update({
    '00415480': 'renderSync',  '00415420': 'renderFlush',  '004e77b0': 'loadData',
    '00416a10': 'touchTextures', '00505df0': 'hataNoop',    '00409ef0': 'anmReset',
    '004db060': 'bgmPlay',     '0041e3d0': 'bgmIsPlaying', '0041e500': 'bgmStop',
    '0041f4e0': 'unloadBank',  '00464d30': 'anmObjFree',
})
for a in set(re.findall(r'FUN_(004[ef][0-9a-f]{4})\(', fn)):
    g.CALLS.setdefault(a, 'demo_' + a)
out = g.translate(fn, 'DemoTask')
out = out.replace('void DemoTask::op_004e3ae0() {', 'Co<> DemoTask::director() {')
if 'DAT_' in out or 'TS16(0x007a4' in out:
    raise SystemExit('an engine global is left: ' + re.search(r'.*(DAT_|TS16\(0x007a4).*', out).group(0))
open(sys.argv[2], 'w').write(
    '// GENERATED by tools/gen/gen_demo_director.py (tools/ghidra2cpp.py) from the Ghidra export. Do not edit.\n'
    '// NOLINTBEGIN\n' + out + '// NOLINTEND\n')
print('wrote', sys.argv[2])
