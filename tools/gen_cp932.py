#!/usr/bin/env python3
"""Generate game/text/cp932_table.gen.hpp from Python's cp932 codec.

Double-byte table: lead 0x81-0x9f / 0xe0-0xfc, trail 0x40-0xfc; 0 = unmapped.
Usage: python3 -I tools/gen_cp932.py game/text/cp932_table.gen.hpp
"""
import sys

leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
rows = []
for lead in leads:
    row = []
    for trail in range(0x40, 0xFD):
        try:
            ch = bytes([lead, trail]).decode("cp932")
            row.append(ord(ch) if len(ch) == 1 and ord(ch) < 0x10000 else 0)
        except UnicodeDecodeError:
            row.append(0)
    rows.append(row)
body = ",\n    ".join(", ".join(f"0x{v:04x}" for v in r) for r in rows)
with open(sys.argv[1], "w") as f:
    f.write("// GENERATED by tools/gen_cp932.py from Python's cp932 codec. Do not edit.\n"
            "#pragma once\n#include <array>\n#include <cstdint>\n\nnamespace ch::cp932 {\n\n"
            f"inline constexpr int kTrailCount = {0xFD - 0x40};\n"
            f"inline constexpr std::array<std::uint16_t, {len(leads)} * kTrailCount> kDouble{{{{\n    {body}\n}}}};\n\n"
            "} // namespace ch::cp932\n")
print(f"{len(leads)} lead bytes, {sum(1 for r in rows for v in r if v)} mapped pairs")
